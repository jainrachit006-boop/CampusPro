-- Campus Intelligence - RLS Policies
-- =========================================
-- Row Level Security policies for the complaints table.
-- Designed for demo/public access with deliberate scoping.
-- =========================================

-- Enable Row Level Security on the complaints table
ALTER TABLE complaints ENABLE ROW LEVEL SECURITY;

-- Policy: Allow anonymous public to read complaints
-- Used for viewing the dashboard and complaint lists in demo mode.
-- Does not allow inserting, updating, or deleting without authenticated access.
CREATE POLICY "Allow public read access" ON complaints
    FOR SELECT
    TO anon
    USING (true);

-- Policy: Allow authenticated users to insert new complaints
-- Students use this when submitting new complaints through the frontend.
-- The complaint_code is generated by a trigger or the application layer.
CREATE POLICY "Allow authenticated insert" ON complaints
    FOR INSERT
    TO authenticated
    WITH CHECK (true);

-- Policy: Allow authenticated users to update complaint status
-- Administrators and staff can update the status of complaints.
-- Only the status field may be updated to prevent arbitrary data changes.
CREATE POLICY "Allow authenticated update status" ON complaints
    FOR UPDATE
    TO authenticated
    USING (true)
    WITH CHECK (status IN ('RAISED', 'IN_PROGRESS', 'RESOLVED'));

-- Policy: Allow administrators to delete resolved complaints
-- Cleanup policy for maintaining the database.
-- In demo mode, this may be restricted or removed.
DROP POLICY IF "Allow admin delete" ON complaints;
CREATE POLICY "Allow admin delete" ON complaints
    FOR DELETE
    TO authenticated
    USING (status = 'RESOLVED');

-- Policy Note: Anonymous access is deliberately scoped to SELECT only.
-- Insert, update, and delete operations require authenticated sessions.
-- This prevents unauthorized modifications while allowing public viewing
-- of the complaint dashboard for demonstration purposes.
--
-- Implications of anonymous demo access:
-- - Anyone can view the complaint list and dashboard
-- - New complaints can only be submitted by authenticated users (students/staff)
-- - Status updates require administrator authentication
-- - AI summaries and department assignments are managed backend-only
-- - The system remains functional as a demo without requiring user accounts
--   for read access, but all write operations are protected.